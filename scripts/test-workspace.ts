import { strict as assert } from 'node:assert';
import { mkdir, mkdtemp, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { _electron as electron, expect } from '@playwright/test';

const temporary = await mkdtemp(path.join(os.tmpdir(), 'planimulation-workspace-'));
const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined));
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.', `--user-data-dir=${temporary}`], env, timeout: 30_000 });
const errors: string[] = [];
try {
  const page = await app.firstWindow();
  // Electron resolves beforeunload through will-prevent-unload, not a CDP dialog.
  page.on('dialog', () => {});
  page.setDefaultTimeout(15_000);
  await app.evaluate(async ({ clipboard, dialog }) => {
    dialog.showMessageBoxSync = () => 1;
    // Preserve every clipboard format without returning personal clipboard data to the test process.
    (globalThis as unknown as { uxClipboard: Electron.ClipboardItem[] }).uxClipboard = await clipboard.read();
  });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && /WebGL|shader|Content Security Policy/i.test(message.text())) errors.push(message.text()); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(page.locator('body')).toHaveAttribute('data-state', 'ready', { timeout: 30_000 });
  await page.evaluate(() => document.fonts.ready);
  const initialFingerprint = await page.locator('#fingerprint').textContent();
  assert.deepEqual(await page.evaluate(() => {
    const ids = [...document.querySelectorAll('[id]')].map(element => element.id);
    return ids.filter((id, index) => ids.indexOf(id) !== index);
  }), [], 'Every controller binding has exactly one DOM target.');
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/workspace-initial.png', scale: 'css' });
  await expect(page.locator('#inspector-empty')).toBeVisible();
  const worldSeed = await page.locator('#world-name').textContent();
  await page.locator('.world-identity').hover();
  await page.locator('#copy-seed').click();
  await expect(page.locator('#copy-seed')).toHaveAttribute('data-copy-state', 'copied');
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), worldSeed);
  assert.equal(await page.evaluate(async () => {
    try { await window.desktop.copyText('x'.repeat(65_537)); return false; } catch { return true; }
  }), true, 'The clipboard bridge rejects oversized input.');
  await page.locator('#world-name').evaluate(element => { element.textContent = 'x'.repeat(65_537); });
  await page.locator('#copy-seed').click();
  await expect(page.locator('#copy-seed')).toHaveAttribute('data-copy-state', 'failed');
  await expect(page.locator('#copy-seed')).toHaveAttribute('aria-label', 'Copy failed. Try again.');
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), worldSeed, 'A failed copy keeps the clipboard intact.');
  await page.locator('#world-name').evaluate((element, seed) => { element.textContent = seed; }, worldSeed);
  await page.locator('#copy-seed').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#copy-seed')).toHaveAttribute('data-copy-state', 'copied');
  await expect(page.locator('#copy-seed')).not.toHaveAttribute('data-copy-state', /.+/);
  await expect(page.locator('#copy-seed')).toHaveAttribute('aria-label', 'Copy world seed');
  await page.locator('[data-dialog="details-dialog"]').click();
  await page.locator('[data-copy-target="fingerprint"]').click();
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), initialFingerprint);
  await page.keyboard.press('Escape');
  await page.locator('#status-details').click();
  const statusMessage = await page.locator('#full-status').textContent();
  await page.locator('[data-copy-target="full-status"]').click();
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), statusMessage);
  await page.keyboard.press('Escape');
  await page.locator('#layer-filter').fill('temperature');
  await expect(page.locator('.layer:visible')).toHaveCount(1);
  await page.locator('#layer-filter').press('ArrowDown');
  await expect(page.locator('[data-layer="temperature"]')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#climate-context')).toBeVisible();
  await page.locator('#temperature-month').selectOption('9');
  await expect(page.locator('#map')).toHaveAttribute('data-temperature-month', '9');
  await page.locator('#layer-filter').fill('no-such-layer');
  await expect(page.locator('#layer-empty')).toBeVisible();
  await page.locator('#layer-filter').press('Escape');
  await page.locator('[data-layer="surface"]').click();
  await expect(page.locator('#climate-context')).toBeHidden();
  await expect(page.locator('#fingerprint')).toHaveText(initialFingerprint!);

  // Inspection remains beside the map and exposes real model values.
  const canvas = page.locator('#map');
  await canvas.click();
  await expect(page.locator('#selection-heading')).toBeVisible();
  await expect(page.locator('#primary-region-details')).toContainText('Initial water depth');
  await expect(page.locator('#inspector-empty')).toBeHidden();
  await page.locator('#copy-region').click();
  await expect(page.locator('#copy-region')).toHaveAttribute('data-copy-state', 'copied');
  const regionCopy = await app.evaluate(({ clipboard }) => clipboard.readText());
  assert.ok(regionCopy.includes(`World seed\t${worldSeed}`));
  assert.ok(regionCopy.includes('Initial water depth\t'));
  assert.ok(!regionCopy.includes('Connected neighbors\t'), 'Collapsed properties are not presented as visible values.');
  await page.locator('#primary-region-details dd').first().dblclick();
  assert.ok(await page.evaluate(() => !!window.getSelection()?.toString()), 'Values remain selectable for ordinary copying.');
  await page.evaluate(() => window.getSelection()?.removeAllRanges());
  await page.locator('#tab-factors').click();
  assert.equal(await page.locator('#tab-factors').evaluate(button => button.matches(':focus-visible')), false);
  await expect(page.locator('#copy-region')).toBeHidden();
  await expect(page.locator('#water-note')).toBeVisible();
  await page.locator('#tab-factors').press('ArrowLeft');
  await expect(page.locator('#tab-overview')).toBeFocused();
  assert.equal(await page.locator('#tab-overview').evaluate(button => button.matches(':focus-visible')), true);
  assert.ok(await page.locator('#tab-overview').evaluate(button => Number.parseFloat(getComputedStyle(button).outlineOffset) < 0), 'Keyboard focus stays within the tab.');
  await page.screenshot({ path: 'artifacts/workspace-selected.png', scale: 'css' });
  await page.locator('#all-region-properties summary').click();
  await expect(page.locator('#selection-details')).toContainText('Connected neighbors');
  await page.locator('#copy-region').click();
  const expandedCopy = await app.evaluate(({ clipboard }) => clipboard.readText());
  assert.ok(expandedCopy.includes('Connected neighbors\t'));
  assert.equal(expandedCopy.split('\n').filter(row => row.startsWith('Initial water depth\t')).length, 1, 'Expanded values are not duplicated.');
  const oldWidth = await page.locator('#resize-inspector').getAttribute('aria-valuenow');
  await page.locator('#resize-inspector').focus();
  await page.keyboard.press('ArrowLeft');
  await expect(page.locator('#resize-inspector')).toHaveAttribute('aria-valuenow', String(Number(oldWidth) + 10));
  await page.locator('#resize-inspector').dblclick();
  const separator = await page.locator('#resize-layers').boundingBox();
  assert.ok(separator);
  await page.mouse.move(separator.x + separator.width / 2, separator.y + 100);
  await page.mouse.down();
  await page.mouse.move(separator.x + separator.width / 2 + 30, separator.y + 100);
  await page.mouse.up();
  await expect(page.locator('#resize-layers')).toHaveAttribute('aria-valuenow', '278');
  await page.locator('#resize-layers').dblclick();
  await page.locator('#toggle-layers').click();
  await expect(page.locator('#layers-pane')).toHaveAttribute('inert', '');
  await page.keyboard.press('Control+k');
  await expect(page.locator('#layer-filter')).toBeFocused();
  await page.locator('#display-trigger').click();
  await page.locator('#exaggeration').selectOption('25');
  await page.keyboard.press('Escape');
  await page.locator('[data-view="globe"]').click();
  await expect(canvas).toHaveAttribute('data-view', 'globe');
  await page.screenshot({ path: 'artifacts/workspace-globe.png', scale: 'css' });
  await page.locator('[data-view="flat"]').click();
  await expect(page.locator('#fingerprint')).toHaveText(initialFingerprint!);

  // An experiment can be saved, advanced, restored, and continued through the new shell.
  await page.locator('#moisture-start').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '0');
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  await expect(page.locator('#moisture-model')).toBeDisabled();
  await expect(page.locator('#unsaved-indicator')).toBeVisible();
  await page.locator('[data-group="seasonal"] summary').click();
  await page.locator('[data-layer="vaporWater"]').click();
  await expect(page.locator('#layer-reading')).toBeVisible();
  await expect(page.locator('#layer-reading-value')).toContainText('mm WE');
  const initialVapor = await page.locator('#layer-reading-value').textContent();
  await page.locator('#moisture-interval').selectOption('3600');
  await page.locator('#moisture-step').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '3600');
  await expect(page.locator('#layer-reading-value')).not.toHaveText(initialVapor!);
  await page.locator('#copy-region').click();
  const seasonalCopy = await app.evaluate(({ clipboard }) => clipboard.readText());
  assert.ok(seasonalCopy.includes((await page.locator('#layer-reading-value').textContent())!));
  assert.ok(seasonalCopy.includes((await page.locator('#layer-reading-scope').textContent())!));
  assert.ok(seasonalCopy.includes('Seasonal model\tbaseline'));
  await page.locator('[data-layer="surface"]').click();
  await page.locator('#copy-region').click();
  const seasonalSurfaceCopy = await app.evaluate(({ clipboard }) => clipboard.readText());
  assert.ok(seasonalSurfaceCopy.includes(`Seasonal time\t${await page.locator('#moisture-time').textContent()}`), 'Seasonal exchange retains its clock even on a static layer.');
  await page.locator('[data-layer="vaporWater"]').click();
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  await page.locator('#tab-budgets').click();
  await expect(page.locator('#moisture-budget-details')).toContainText('Total current owned water');
  const checkpoint = path.join(temporary, 'seasonal.json');
  await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }); }, checkpoint);
  await page.locator('#file-trigger').click();
  await page.locator('#save-seasonal').click();
  await expect(page.locator('#status')).toContainText('checkpoint saved');
  await expect(page.locator('#unsaved-indicator')).toBeHidden();
  assert.equal(JSON.parse(await readFile(checkpoint, 'utf8')).elapsedSeconds, 3600);
  await page.locator('#moisture-step').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '7200');
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  await page.locator('[data-dialog="world-dialog"]').click();
  await page.locator('#seed').click();
  assert.equal(await page.locator('#seed').evaluate(input => getComputedStyle(input).outlineStyle), 'none');
  assert.equal(await page.locator('#seed').evaluate(input => getComputedStyle(input).borderColor), 'rgb(228, 173, 67)', 'Hover does not erase the focused field border.');
  await page.emulateMedia({ forcedColors: 'active' });
  assert.equal(await page.locator('#seed').evaluate(input => getComputedStyle(input).outlineStyle), 'solid', 'System contrast mode retains a visible field outline.');
  await page.emulateMedia({ forcedColors: 'none' });
  await page.screenshot({ path: 'artifacts/workspace-new-world.png', scale: 'css' });
  await page.locator('#generate').click();
  await expect(page.locator('#replace-dialog')).toBeVisible();
  await page.locator('#keep-world').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '7200');
  await page.locator('#world-dialog [data-close-dialog]').click();
  await app.evaluate(({ dialog }, source) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [source] }); }, checkpoint);
  await page.locator('#file-trigger').click();
  await page.locator('#open-seasonal').click();
  await page.locator('#replace-world').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '3600', { timeout: 120_000 });
  await expect(page.locator('body')).toHaveAttribute('data-state', 'ready');
  await page.locator('#moisture-step').click();
  await expect(canvas).toHaveAttribute('data-moisture-seconds', '7200');
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  await page.locator('#moisture-play').click();
  await expect(page.locator('#moisture-play')).toHaveText('Pause');
  await page.locator('#tab-manual').click();
  await expect(page.locator('#manual-availability')).toBeVisible();
  await page.locator('#pause-active').click();
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused', { timeout: 30_000 });
  await page.locator('#tab-seasonal').click();
  const paused = await canvas.getAttribute('data-moisture-seconds');
  await page.waitForTimeout(150);
  assert.equal(await canvas.getAttribute('data-moisture-seconds'), paused);
  await page.screenshot({ path: 'artifacts/workspace-seasonal.png', scale: 'css' });

  // Narrow layouts expose the same inspector without sacrificing the map viewport.
  for (const width of [1280, 1024, 760, 390]) {
    await page.setViewportSize({ width, height: 800 });
    if (width <= 1150) {
      await page.locator('#toggle-inspector').click();
      await expect(page.locator('#inspector-pane')).toBeVisible();
      await page.keyboard.press('Escape');
      await expect(page.locator('#inspector-pane')).toHaveAttribute('inert', '');
    }
    const bounds = await canvas.boundingBox();
    assert.ok(bounds && bounds.width > 200 && bounds.height > 120, `${width}px retains a usable map.`);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${width}px has no document overflow.`);
    await page.screenshot({ path: `artifacts/workspace-${width}.png`, scale: 'css' });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await app.evaluate(({ dialog, BrowserWindow }) => {
    dialog.showMessageBoxSync = () => 0;
    BrowserWindow.getAllWindows()[0].close();
  });
  await expect(page.locator('body')).toHaveAttribute('data-state', 'ready');
  await page.locator('#moisture-step').click();
  await expect(canvas).not.toHaveAttribute('data-moisture-seconds', paused!);
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  const beforeCanceledReload = await canvas.getAttribute('data-moisture-seconds');
  await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].webContents.reload(); });
  await page.waitForTimeout(150);
  await expect(canvas).toHaveAttribute('data-moisture-seconds', beforeCanceledReload!);
  await page.locator('#moisture-step').click();
  await expect(canvas).not.toHaveAttribute('data-moisture-seconds', beforeCanceledReload!);
  await expect(page.locator('body')).toHaveAttribute('data-seasonal-water', 'paused');
  await page.locator('#resize-inspector').focus();
  await page.keyboard.press('ArrowLeft');
  const rememberedWidth = await page.locator('#resize-inspector').getAttribute('aria-valuenow');
  if (await page.locator('[data-group="water"]').evaluate(group => (group as HTMLDetailsElement).open)) await page.locator('[data-group="water"] summary').click();
  await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1; });
  await page.reload();
  await expect(page.locator('body')).toHaveAttribute('data-state', 'ready', { timeout: 30_000 });
  await expect(page.locator('#resize-inspector')).toHaveAttribute('aria-valuenow', rememberedWidth!);
  assert.equal(await page.locator('[data-group="water"]').evaluate(group => (group as HTMLDetailsElement).open), false);
  await canvas.click({ position: { x: 250, y: 220 } });
  await page.screenshot({ path: 'artifacts/workspace-final.png', scale: 'css' });
  assert.deepEqual(errors, []);
  console.log('Workspace checks passed: clipboard, focus, selection, navigation, inspection, display, seasonal checkpoint continuation, replacement protection, pause, and responsive layouts.');
} finally {
  await app.evaluate(async ({ clipboard, dialog }) => {
    dialog.showMessageBoxSync = () => 1;
    const saved = (globalThis as unknown as { uxClipboard?: Electron.ClipboardItem[] }).uxClipboard;
    if (saved) { if (saved.length) await clipboard.write(saved); else clipboard.clear(); }
  }).catch(() => {});
  await app.close();
}
